  var STORAGE_KEY = "kzielts_lang";
  var DEFAULT_LANG = "ru";
  var LABELS = { ru: "RU", kk: "ҚАЗ", en: "EN" };

  function getPath(lang, key) {
    var parts = key.split(".");
    var node = translations[lang];
    for (var i = 0; i < parts.length; i++) {
      if (node == null) return undefined;
      node = node[parts[i]];
    }
    return node;
  }

  function currentLang() {
    try {
      var stored = localStorage.getItem(STORAGE_KEY);
      if (stored && translations[stored]) return stored;
    } catch (e) {}
    return DEFAULT_LANG;
  }

  function applyLanguage(lang) {
    if (!translations[lang]) lang = DEFAULT_LANG;
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var value = getPath(lang, el.getAttribute("data-i18n"));
      if (value !== undefined) el.textContent = value;
    });

    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var value = getPath(lang, el.getAttribute("data-i18n-html"));
      if (value !== undefined) el.innerHTML = value;
    });

    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
      var map = JSON.parse(el.getAttribute("data-i18n-attr"));
      Object.keys(map).forEach(function (attr) {
        var value = getPath(lang, map[attr]);
        if (value !== undefined) el.setAttribute(attr, value);
      });
    });

    var titleKey = document.body.getAttribute("data-i18n-title");
    if (titleKey) {
      var t = getPath(lang, titleKey);
      if (t !== undefined) document.title = t;
    }
    var descKey = document.body.getAttribute("data-i18n-desc");
    if (descKey) {
      var d = getPath(lang, descKey);
      var meta = document.querySelector('meta[name="description"]');
      if (meta && d !== undefined) meta.setAttribute("content", d);
    }

    document.querySelectorAll("[data-lang-label]").forEach(function (el) {
      el.textContent = LABELS[lang] || lang.toUpperCase();
    });

    document.querySelectorAll("[data-lang-option]").forEach(function (el) {
      var isActive = el.getAttribute("data-lang-option") === lang;
      el.classList.toggle("font-semibold", isActive);
      el.classList.toggle("text-gray-900", isActive);
      el.classList.toggle("bg-gray-50", isActive);
    });

    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}

    window.__currentLang = lang;

    if (typeof window.onLanguageChange === "function") {
      window.onLanguageChange(lang);
    }
  }

  window.i18n = {
    get: function (key) {
      return getPath(currentLang(), key);
    },
    apply: applyLanguage,
    current: currentLang
  };

  document.addEventListener("DOMContentLoaded", function () {
    applyLanguage(currentLang());
  });
